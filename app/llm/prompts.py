def topics_block(topics: list[str]) -> str:
    return "Темы класса: " + "; ".join(f"«{title}»" for title in topics) + "."


def fragments_block(fragments: list[str]) -> str:
    if not fragments:
        return ""
    joined = "\n---\n".join(fragment[:1500] for fragment in fragments)
    return f"Фрагменты урока, загруженные учителем:\n{joined}"
