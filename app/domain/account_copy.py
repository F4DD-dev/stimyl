def cabinet_text(url: str, public_id: str, code: str) -> str:
    lines = [
        f"Заявка {public_id}. Код {code}. Действует 5 минут и только один раз.",
        "Если ссылка не открылась, на странице кабинета введи заявку и код.",
    ]
    if url:
        lines.insert(0, url)
    return " ".join(lines)
