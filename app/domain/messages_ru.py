def similar_example(state: object, prompt: str, answer: str) -> str:
    return f"{say(state, 'similar')} {prompt} Получается {answer}."


def say(state: object, key: str) -> str:
    """Следующая реплика из набора. Подряд одна и та же не повторяется."""
    options = LINES[key]
    cursor = int(getattr(state, "line_cursor", 0) or 0)
    last = str(getattr(state, "last_line", "") or "")
    slot = cursor % len(options)
    marker = f"{key}:{slot}"
    if marker == last:
        slot = (slot + 1) % len(options)
        marker = f"{key}:{slot}"
    setattr(state, "last_line", marker)
    setattr(state, "line_cursor", cursor + 1)
    return options[slot]
